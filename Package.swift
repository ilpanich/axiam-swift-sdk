// One manifest. Through 1.1.x the package also shipped `Package@swift-6.0.swift`,
// because the floor was tools-version 5.9 and `.swiftLanguageMode` needs 6.0;
// with the floor at 6.2 every toolchain that can resolve the package can read
// the language-mode setting, so the version-specific manifest would only shadow
// this file. It is gone, and so is the parity test that held the two together.
//
// Every target below is compiled in **Swift 6 language mode**: full
// strict-concurrency checking as errors. The mode is set per target, so it
// governs this package's sources and nothing else in the dependency graph.
// Under tools-version 6.x Swift 6 is already the default — the settings are
// spelled out anyway so a reader need not know that rule, and
// `VersionPolicyTests` pins them.
